-- SPCS - Automação
-- Base de mapas DNP3 por modelo de relé / aplicação, extraída de
-- 'Padrões AT - Mapas DNP3.xlsx' (abas INICIO + por aplicação).
-- Alimenta o motor de comparação Log de Eventos x Mapa de Pontos:
-- o relé/aplicação escolhido no Cadastro de Automação define qual
-- mapa_dnp3_aplicacoes.aplicacao usar ao conferir o log de ensaios.

create table mapas_dnp3_aplicacoes (
  id uuid primary key default gen_random_uuid(),
  modelo_rele text not null,       -- ex: SEL-751, SEL-311C, SEL-787...
  aplicacao text not null,         -- ex: GERAL, BC AT, TRANSF DISPARO...
  nome_aba_origem text not null unique, -- nome da aba no Excel de origem
  versao_referencia text,
  created_at timestamptz not null default now()
);

create table mapas_dnp3_pontos (
  id uuid primary key default gen_random_uuid(),
  aplicacao_id uuid not null references mapas_dnp3_aplicacoes(id) on delete cascade,
  tipo text,            -- BI/BO/AI/AO conforme planilha
  posicao int,          -- índice DNP3 (Posicao na planilha)
  wordbit text not null,-- tag padrão do relé (ex: SV04T, 52A, IN302)
  descricao text,
  valor_0 text,
  valor_1 text,
  comissionado boolean,
  observacoes text
);
create index on mapas_dnp3_pontos (aplicacao_id);
create index on mapas_dnp3_pontos (upper(wordbit));

